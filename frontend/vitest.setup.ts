import 'fake-indexeddb/auto'
import '@/i18n'

// jsdom doesn't implement matchMedia; theme-store.ts reads it at module load.
Object.defineProperty(window, 'matchMedia', {
  writable: true,
  value: (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }),
})
